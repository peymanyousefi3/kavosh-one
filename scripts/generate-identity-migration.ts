import { writeFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { Kysely, PGliteDialect } from 'kysely';
import { getMigrations } from 'better-auth/db/migration';
import { createIdentity } from '../src/auth/config.ts';
import { IdentityStore } from '../src/auth/store.ts';

const engine=new PGlite();
await engine.exec('CREATE SCHEMA identity');
const db=new Kysely<unknown>({dialect:new PGliteDialect({pglite:engine})}).withSchema('identity');
try {
  const config={origin:'https://migration.example',secret:'synthetic-schema-generation-secret-000000',production:false};
  const store=new IdentityStore(db,config.secret);
  const auth=createIdentity(db,store,{async email(){throw new Error('Schema generation must not send mail');},async sms(){throw new Error('Schema generation must not send SMS');}},config);
  const plan=await getMigrations(auth.options);
  const sql=await plan.compileMigrations();
  await writeFile(new URL('../db/migrations/002_identity.sql',import.meta.url),'-- Generated by Better Auth 1.7.15 getMigrations; review before applying.\nCREATE SCHEMA identity;\nREVOKE ALL ON SCHEMA identity FROM PUBLIC;\n'+sql+'\n');
} finally { await db.destroy(); }
